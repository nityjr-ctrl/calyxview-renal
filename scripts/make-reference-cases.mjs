// Publishes the real KiTS23-derived meshes and their computed nephrometry to
// the web bundle.
//
// Two rules shape this script:
//   1. The deploy bundle scan forbids KiTS cohort identifiers in any published
//      pathname or text file, so every case is republished under a neutral
//      letter. The mapping back to the cohort stays in docs/REFERENCE-CASES.md,
//      which is never deployed.
//   2. Nephrometry is read from the pipeline's own planning.json rather than
//      retyped, so the published numbers are the ones renalplan computed.
//
//   node scripts/make-reference-cases.mjs [path-to-glb-source-dir]

import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE_MESHES = process.argv[2] ?? '/home/user/CalyxView/web/public/models';
const CASES = [
  { letter: 'a', cohortIndex: 0 },
  { letter: 'b', cohortIndex: 1 },
  { letter: 'c', cohortIndex: 2 },
  { letter: 'd', cohortIndex: 3 },
  { letter: 'e', cohortIndex: 4 },
];

const STRUCTURES = {
  parenchyma: { label: 'Kidney', colour: '#c9b79b', opacity: 0.34, visible: true },
  tumour: { label: 'Tumour', colour: '#d85c60', opacity: 1, visible: true },
  cyst: { label: 'Cyst', colour: '#8fb8d8', opacity: 0.7, visible: true },
  ribs: { label: 'Ribs', colour: '#d8d2c4', opacity: 0.5, visible: false },
  psoas: { label: 'Psoas', colour: '#b98b7a', opacity: 0.45, visible: false },
  colon: { label: 'Colon', colour: '#c8a06a', opacity: 0.45, visible: false },
  spleen: { label: 'Spleen', colour: '#a8737d', opacity: 0.45, visible: false },
  liver: { label: 'Liver', colour: '#9d7a6b', opacity: 0.4, visible: false },
  skin: { label: 'Body outline', colour: '#8fa0ad', opacity: 0.09, visible: false },
};

function meshNames(buffer) {
  // Read the JSON chunk of the GLB container to discover the node names.
  const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
  const chunkLength = view.getUint32(12, true);
  const json = JSON.parse(new TextDecoder().decode(buffer.subarray(20, 20 + chunkLength)));
  return (json.meshes ?? []).map((mesh) => mesh.name).filter(Boolean);
}

await mkdir('public/models', { recursive: true });

const published = [];
const provenance = [];

for (const { letter, cohortIndex } of CASES) {
  const cohortId = `case_${String(cohortIndex).padStart(5, '0')}`;
  const sourceGlb = join(SOURCE_MESHES, `${cohortId}.glb`);
  if (!existsSync(sourceGlb)) {
    console.warn(`skipped ${letter}: no mesh at ${sourceGlb}`);
    continue;
  }

  const target = `reference-${letter}.glb`;
  await copyFile(sourceGlb, join('public/models', target));

  const names = meshNames(await readFile(sourceGlb));
  const planning = JSON.parse(
    await readFile(join('pipeline/results/cases', cohortId, 'planning.json'), 'utf8'),
  );
  const renal = planning.nephrometry.renal;
  const padua = planning.nephrometry.padua;

  published.push({
    id: `reference-${letter}`,
    label: `Reference kidney ${letter.toUpperCase()}`,
    mesh: `/models/${target}`,
    structures: names.map((name) => ({
      name,
      ...(STRUCTURES[name] ?? { label: name, colour: '#9aa7b2', opacity: 0.5, visible: false }),
    })),
    nephrometry: {
      renalLabel: planning.nephrometry.renalLabel,
      renalTotal: renal.total,
      renalComplexity: renal.complexity,
      paduaTotal: padua.total,
      paduaComplexity: padua.complexity,
      radiusCm: renal.radius_cm,
      exophyticFraction: renal.exophytic_fraction,
      nearnessMm: renal.nearness_mm,
      face: renal.ap,
      polarLocation: padua.polar_location,
      rim: padua.rim,
      locationDetail: renal.location_detail,
      hilar: renal.hilar,
    },
    runtimeSeconds: planning.provenance.runtimeSeconds,
    mesh_settings: planning.provenance.mesh,
  });

  provenance.push(`| reference-${letter} | \`${cohortId}\` | ${names.join(', ')} |`);
}

const banner = `// GENERATED by scripts/make-reference-cases.mjs. Do not edit by hand.
//
// Real kidneys from the KiTS23 reference labels, meshed by the pipeline and
// republished here under neutral letters. Every number below was computed by
// renalplan from the geometry and copied out of that case's planning.json.
// KiTS23 is used under CC BY-NC-SA 4.0.
`;

await writeFile(
  'lib/reference-cases.ts',
  `${banner}
export type ReferenceStructure = {
  name: string;
  label: string;
  colour: string;
  opacity: number;
  visible: boolean;
};

export type ReferenceCase = {
  id: string;
  label: string;
  mesh: string;
  structures: ReferenceStructure[];
  nephrometry: {
    renalLabel: string;
    renalTotal: number;
    renalComplexity: string;
    paduaTotal: number;
    paduaComplexity: string;
    radiusCm: number;
    exophyticFraction: number;
    nearnessMm: number;
    face: string;
    polarLocation: string;
    rim: string;
    locationDetail: string;
    hilar: boolean;
  };
  runtimeSeconds: number;
};

export const referenceCases: ReferenceCase[] = ${JSON.stringify(
    published.map(({ mesh_settings, ...rest }) => rest),
    null,
    2,
  )};

export const referenceCaseCount = ${published.length};
`,
  'utf8',
);

await writeFile(
  'docs/REFERENCE-CASES.md',
  `# Published reference cases

The site publishes ${published.length} real kidneys built from the KiTS23 reference
labels. They appear under neutral letters because the deploy bundle scan forbids
cohort identifiers in any published pathname or text file. This file records the
mapping and is never deployed.

Regenerate with:

\`\`\`
node scripts/make-reference-cases.mjs [path-to-glb-source-dir]
\`\`\`

| Published as | Cohort case | Meshes in the file |
| --- | --- | --- |
${provenance.join('\n')}

Nephrometry shown on the site is read from each case's \`planning.json\`, as
computed by renalplan from the mesh geometry. KiTS23 is used under
CC BY-NC-SA 4.0; these meshes are a derivative of the reference labels and carry
the same non-commercial share-alike terms.
`,
  'utf8',
);

console.log(`published ${published.length} reference cases`);
